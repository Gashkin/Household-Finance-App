import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unlockFixture, BACKEND_URL } from './workspace-helper';
test.use({ extraHTTPHeaders: { 'X-Workspace-Request': '1' } });
test.beforeEach(unlockFixture);

test('capture cash evidence, inspect and download a reproducible debt decision', async ({ page, request }, testInfo) => {
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Cash position',exact:true})).toBeVisible();
  await expect(page.getByText('Loading saved cash position…')).toBeHidden();
  const editor = page.locator('.cash-editor');
  if(!await page.getByLabel('Evidence source or reference').isVisible())await editor.locator('summary').click();
  await page.getByLabel('Evidence source or reference').fill('Synthetic bank statement');
  await page.getByLabel('Evidence status').selectOption('REVIEWED');
  await page.getByLabel('Protected reserve (€)', { exact: true }).fill('400');
  await page.getByLabel('Cash accounts entry 1 name').fill('Demo current account');
  await page.getByLabel('Cash accounts entry 1 euros').fill('1000');
  await page.getByRole('button', { name: '+ Add commitment', exact: true }).click();
  await page.getByLabel('Upcoming commitments entry 1 name').fill('Demo bill');
  await page.getByLabel('Upcoming commitments entry 1 euros').fill('100');
  await page.getByRole('button', { name: 'Save cash position', exact: true }).click();
  await page.getByRole('button', { name: 'Use this cash position in debt comparison', exact: true }).click();
  await expect(page.getByLabel('Available cash (€)', { exact: true })).toHaveValue('900.00');
  await page.getByLabel('Debt outstanding (€)', { exact: true }).fill('60');
  await page.getByLabel('Annual interest rate (%)', { exact: true }).fill('0.69999999999999999');
  await page.getByLabel('Monthly repayment (€)', { exact: true }).fill('60');
  await page.getByLabel('Extra repayment now (€)', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Compare scenarios', exact: true }).click();
  const preview = page.getByRole('region', { name: 'Review your report before downloading' });
  await expect(preview).toContainText('0.69999999999999999%');
  await expect(preview).toContainText('Synthetic bank statement');
  await expect(preview).toContainText('Manually reviewed');
  await expect(preview).toContainText('No fees, penalties');
  const downloadEvent = page.waitForEvent('download');
  await preview.getByRole('button', { name: 'Download JSON report' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('debt-comparison.json');
  const report = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(report.input.annualRatePercent).toBe('0.69999999999999999');
  expect(report.result.baseline.interestMinor).toBe(3);
  expect(report.cashEvidence.sourceNote).toBe('Synthetic bank statement');
  expect(report.cashEvidence.committedMinor).toBe(10000);
  expect(report.input.cashPositionSnapshotId).toBe(report.cashEvidence.id);
  const replay = await request.post(`${BACKEND_URL}/api/debt-scenarios/report`, { data: report.input });
  expect(replay.ok()).toBeTruthy();
  expect((await replay.json()).result).toEqual(report.result);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath('report-preview.png'), fullPage: true });
  await page.getByLabel('Extra repayment now (€)', { exact: true }).fill('1');
  await expect(preview).toBeHidden();
  await expect(page.getByRole('button', { name: 'Download JSON report' })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
});

test('service outage and obsolete responses cannot yield an export', async ({ page }) => {
  await page.goto('/');
  await page.route('**/api/debt-scenarios/report', route => route.abort('failed'));
  await page.getByRole('button', { name: 'Compare scenarios', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Cannot reach the financial calculation service');
  await expect(page.getByRole('button', { name: 'Download JSON report' })).toHaveCount(0);
  await page.unroute('**/api/debt-scenarios/report');
  let release!: () => void;
  const paused = new Promise<void>(resolve => { release = resolve; });
  let started!: () => void;
  const received = new Promise<void>(resolve => { started = resolve; });
  await page.route('**/api/debt-scenarios/report', async route => {
    const response = await route.fetch(); started(); await paused; await route.fulfill({ response });
  });
  await page.getByRole('button', { name: 'Compare scenarios', exact: true }).click();
  await received;
  await page.getByLabel('Debt outstanding (€)', { exact: true }).fill('9000');
  const completed = page.waitForResponse(response => response.url().endsWith("/api/debt-scenarios/report"));
  release();
  await (await completed).finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(page.getByRole('button', { name: 'Download JSON report' })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Side-by-side comparison' })).toHaveCount(0);
});
